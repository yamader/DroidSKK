  fun findDropping(s: String): Pair<String, String> {
    val buf = StringBuilder()
    var cur = s
    var res = find(cur)
    while (res == null) {
      val c = cur.first()
      if (c !in ('A'..'Z').plus('a'..'z')) buf.append(c)
      cur = cur.drop(1)
      res = find(cur)
    }
    return res.first to (buf.toString() + res.second)
  }

  private fun find(s: String) =
    romkana.keys.find { s.startsWith(it) }?.let { s.drop(it.length) to it }
      ?: romkana.keys.find { it.startsWith(s) }?.let { s to "" }

